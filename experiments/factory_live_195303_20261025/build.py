#!/usr/bin/env python3
"""Build canonical experiment sources using package CMake, without historic objects.

ROS ament package metadata and install hooks are generated by the same package
CMakeLists; no historical link.txt or prebuilt application library is consumed.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

HERE=Path(__file__).resolve().parent
SOURCE=HERE/'source'
DEFAULT=HERE.parents[1]/'captures/field_frontend_z_init_20261024_001/build'

def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

PACKAGES={'common','msgs','map','mapping','frontend'}
def source_hashes():
    bases=[SOURCE/'frontend',SOURCE/'src']+[p for p in (SOURCE/'third_party').iterdir() if p.is_dir()]
    # Hash the bounded source trees, including .cc, .cmake and ROS interfaces.
    # An extension allowlist can silently omit real compiler/generator inputs.
    return {str(p):dict(sha256=digest(p)) for base in bases for p in base.rglob('*')
            if p.is_file() and '.git' not in p.parts and '__pycache__' not in p.parts}

def check_build_coverage(previous,current,selected):
    """Never bind unbuilt application binaries to changed/deleted dependencies."""
    if selected==PACKAGES:return
    if not previous:raise ValueError('first identity requires all packages; rerun without --only')
    old=previous['sources'];changed={p for p in set(old)|set(current) if old.get(p)!=current.get(p)}
    required=set()
    for name in changed:
        relative=Path(name).relative_to(SOURCE).parts
        if relative[0]=='frontend':required.update(['frontend','mapping'])  # shared startup trace dependency
        elif relative[0]=='third_party' or relative[:2]==('src','a2w_fastlio_common'):required.update(['common','map','mapping'])
        elif relative[:2]==('src','a2w_fastlio_msgs'):required.update(['msgs','mapping'])
        elif relative[:2]==('src','a2w_fastlio_map'):required.update(['map','mapping'])
        elif relative[:2]==('src','a2w_fastlio_mapping'):required.add('mapping')
        else:required.update(PACKAGES)  # conservative provenance for auxiliary tree changes
    if not required.issubset(selected):
        raise ValueError('changed sources/dependencies were not all selected; missing '+str(sorted(required-selected))+'; rerun without --only')

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--build',type=Path,default=DEFAULT)
    parser.add_argument('--only',nargs='+',choices=['common','msgs','map','mapping','frontend'])
    args=parser.parse_args(); root=args.build.resolve(); root.mkdir(parents=True,exist_ok=True)
    before_sources=source_hashes()
    prior_path=root/'build_manifest.json'
    previous=json.loads(prior_path.read_text()) if prior_path.is_file() else None
    check_build_coverage(previous,before_sources,set(args.only) if args.only else PACKAGES)
    env=dict(os.environ)
    for key in ['AMENT_PREFIX_PATH','CMAKE_PREFIX_PATH','COLCON_PREFIX_PATH','PYTHONPATH','LD_LIBRARY_PATH','MAKEFLAGS']:
        env.pop(key,None)
    raw=subprocess.check_output(['bash','--noprofile','--norc','-c','source /opt/ros/humble/setup.bash && env -0'],env=env)
    env=dict(item.split('=',1) for item in raw.decode().split('\0') if '=' in item)
    dependencies=HERE.parents[1]/'.deps/install'
    packages=[('common','a2w_fastlio_common'),('msgs','a2w_fastlio_msgs'),('map','a2w_fastlio_map'),('mapping','a2w_fastlio_mapping'),('frontend','fast_lio')]
    prefixes=[root/'backend_install'/name for _,name in packages[:-1]]+[dependencies,Path('/opt/ros/humble')]
    env['CMAKE_PREFIX_PATH']=':'.join(map(str,prefixes)); env['AMENT_PREFIX_PATH']=':'.join(map(str,prefixes))
    env['LD_LIBRARY_PATH']=str(dependencies/'lib')+':'+env.get('LD_LIBRARY_PATH','')
    for key,name in packages:
        if args.only and key not in args.only: continue
        source=SOURCE/('frontend' if key=='frontend' else 'src/'+name)
        build=root/('frontend_build' if key=='frontend' else 'backend_build')/name
        install=root/('frontend_install' if key=='frontend' else 'backend_install')/name
        commands=[['cmake','-S',str(source),'-B',str(build),'-DCMAKE_INSTALL_PREFIX='+str(install),
                   '-DCMAKE_BUILD_TYPE=Release','-DBUILD_TESTING=ON','-DPython3_EXECUTABLE=/usr/bin/python3','-DPYTHON_EXECUTABLE=/usr/bin/python3'],
                  ['cmake','--build',str(build),'--parallel','1' if key=='frontend' else '2'],['cmake','--install',str(build)]]
        with (root/(key+'_direct.log')).open('a') as stream:
            for command in commands:
                print('BUILD',key,command,flush=True)
                subprocess.run(command,env=env,stdout=stream,stderr=subprocess.STDOUT,check=True)
    binaries={'frontend':root/'frontend_install/fast_lio/lib/fast_lio/fastlio_mapping',
              'ingress':root/'backend_install/a2w_fastlio_mapping/lib/a2w_fastlio_mapping/mapping_ingress_node',
              'backend':root/'backend_install/a2w_fastlio_mapping/lib/a2w_fastlio_mapping/mapping_backend_node'}
    if all(p.is_file() for p in binaries.values()):
        sources=source_hashes()
        if sources!=before_sources:raise ValueError('source tree changed during build; identity not emitted')
        identity=dict(schema='field_backend_repair_source_build_v1',source_root=str(SOURCE),
                      sources=sources,binaries={r:dict(path=str(p),sha256=digest(p)) for r,p in binaries.items()},
                      dependency_GTSAM=str(dependencies),old_application_objects_reused=False,
                      compile_scope=sorted(set(args.only) if args.only else PACKAGES),partial_source_coverage_checked=True)
        (root/'build_manifest.json').write_text(json.dumps(identity,indent=2)+'\n')
        print('IDENTITY',root/'build_manifest.json',flush=True)

if __name__=='__main__': main()
